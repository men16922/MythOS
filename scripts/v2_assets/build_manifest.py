"""Write src/mythos_ui/src/v2/ui/common/artManifest.ts from the files actually present under
resources/neo-seoul/v2/, so the manifest never lists a missing asset.

  .venv/bin/python scripts/v2_assets/build_manifest.py

Paths are relative to resources/neo-seoul/ (resolve them with `asset()` like every other resource).
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from common import OUT, RES, ROOT

TARGET = ROOT / "src" / "mythos_ui" / "src" / "v2" / "ui" / "common" / "artManifest.ts"
# Boss splash files are named by encounter id; the enemy ids resolve to the same art.
BOSS_ALIASES = {
    "a1_boss_haetae": "haetae",
    "a1_boss_baekho": "baekho_stalker",
    "a1_boss_jujak": "jujak_core",
    "a2_boss_echo_eater": "echo_eater",
    "a2_boss_hyeonmu": "hyeonmu_bastion",
    "a2_boss_arachne": "arachne_queen",
    "a3_boss_ix": "administrator_ix",
    "a3_boss_architect": "architect_omega",
    "a3_boss_warden": "list_warden",
    "a4_boss_io": "io_librarian",
    "a4_boss_blank": "blank_binder",
    "a4_boss_reader": "first_reader",
    "a5_boss_mother": "furnace_mother",
    "a5_boss_kai_zero": "kai_zero",
    "a5_boss_rem": "rem_executor",
    "a6_boss_ix_origin": "ix_origin",
    "a6_boss_omega": "omega_complete",
    "a6_boss_loop_engine": "loop_engine",
    "a6_secret_first_connector": "first_connector",
}
MUSIC_ORDER = [
    "title",
    "hub",
    "map1",
    "map2",
    "map3",
    "event",
    "shop",
    "rest",
    "combat1",
    "combat2",
    "combat3",
    "elite",
    "boss1",
    "boss2",
    "boss_ix",
    "victory",
    "defeat",
    "ending",
]
_IDENT = re.compile(r"^[A-Za-z_$][A-Za-z0-9_$]*$")


def _files(sub: str, ext: str) -> dict[str, str]:
    d = OUT / sub
    if not d.is_dir():
        return {}
    return {
        p.stem: p.relative_to(RES).as_posix()
        for p in sorted(d.iterdir())
        if p.suffix == ext
        and p.is_file()
        and not p.name.startswith(".")
        and ".tmp" not in p.name
        and ".part" not in p.name
    }


def _key(k: str) -> str:
    return k if _IDENT.match(k) or k.isdigit() else f"'{k}'"


def _record(d: dict[str, str], indent: str) -> str:
    if not d:
        return "{}"
    body = "".join(f"{indent}  {_key(k)}: '{v}',\n" for k, v in d.items())
    return "{\n" + body + indent + "}"


def build() -> tuple[str, dict[str, int]]:
    art = _files("art", ".webp")
    maps = _files("map", ".webp")
    acts = {k[3:]: v for k, v in sorted(art.items()) if re.fullmatch(r"act\d", k)}
    map_acts = {k[3:]: v for k, v in sorted(maps.items()) if re.fullmatch(r"act\d", k)}
    bosses = _files("boss", ".webp")
    for enc, enemy in BOSS_ALIASES.items():
        if enc in bosses:
            bosses[enemy] = bosses[enc]
    music_files = _files("music", ".m4a")
    music = {k: music_files[k] for k in MUSIC_ORDER if k in music_files}
    music.update({k: v for k, v in music_files.items() if k not in music})
    groups = {
        "acts": acts,
        "maps": map_acts,
        "arenas": _files("arena", ".webp"),
        "bosses": bosses,
        "endings": _files("ending", ".webp"),
        "events": _files("events", ".webp"),
        "cutscenes": _files("cutscenes", ".webp"),
    }
    cards = _files("cards", ".webp")
    implants = _files("implants", ".webp")
    consumables = _files("consumables", ".webp")

    lines = [
        "// Generated by scripts/v2_assets/build_manifest.py from the files under resources/neo-seoul/v2/ —",
        "// do not edit by hand (rerun the script). Paths are relative to resources/neo-seoul/ (resolve with",
        "// asset()); a key is present only when its file exists. Music files are seamless loops (AAC .m4a).",
        "",
        "export const ART: {",
        "  title: string",
        "  archive: string",
        "  acts: Record<string, string>",
        "  maps: Record<string, string>",
        "  arenas: Record<string, string>",
        "  bosses: Record<string, string>",
        "  endings: Record<string, string>",
        "  events: Record<string, string>",
        "  cutscenes: Record<string, string>",
        "} = {",
        f"  title: '{art.get('title', '')}',",
        f"  archive: '{art.get('archive', '')}',",
    ]
    for name, rec in groups.items():
        lines.append(f"  {name}: {_record(rec, '  ')},")
    lines += [
        "}",
        "",
        f"export const CARD_ART: Record<string, string> = {_record(cards, '')}",
        "",
        f"export const IMPLANT_ART: Record<string, string> = {_record(implants, '')}",
        "",
        f"export const CONSUMABLE_ART: Record<string, string> = {_record(consumables, '')}",
        "",
        f"export const MUSIC: Record<string, string> = {_record(music, '')}",
        "",
    ]
    counts = {
        "art": len(art),
        "maps": len(map_acts),
        **{k: len(v) for k, v in groups.items() if k not in ("acts", "maps")},
        "cards": len(cards),
        "implants": len(implants),
        "consumables": len(consumables),
        "music": len(music),
    }
    return "\n".join(lines), counts


def main() -> int:
    text, counts = build()
    if not TARGET.exists() or TARGET.read_text() != text:
        TARGET.write_text(text)
        print(f"wrote {TARGET.relative_to(ROOT)}")
    else:
        print("manifest unchanged")
    print(" ".join(f"{k}={v}" for k, v in counts.items()))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
