"""Write src/mythos_ui/src/v2/ui/common/spriteManifest.ts from the WebPs that exist on disk.

    .venv/bin/python scripts/v2_assets/sprites/build_manifest.py

Only files present under resources/neo-seoul/v2/sprites/ are listed, so the UI can fall back to the
classic sprite whenever a key/pose is missing.
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from specs import MANIFEST_TS, SPRITES, out_path

POSES = ("idle", "attack", "hit", "guard", "skill", "cover")


def main() -> None:
    sprites: dict[str, dict[str, str]] = {}
    for s in SPRITES:
        poses = {
            p: f"v2/sprites/{out_path(s.key, p).name}" for p in POSES if out_path(s.key, p).exists()
        }
        if "idle" in poses:  # a key without its idle frame is not usable
            sprites[s.key] = poses
    enemy = {eid: s.key for s in SPRITES if s.key in sprites for eid in s.enemy_ids}
    arche = {aid: s.key for s in SPRITES if s.key in sprites for aid in s.archetype_ids}

    def q(v: str) -> str:
        return "'" + v + "'"

    lines = [
        "// Generated by scripts/v2_assets/sprites/build_manifest.py from the files under",
        "// resources/neo-seoul/v2/sprites/ — do not edit by hand (rerun the script). Paths are relative to",
        "// resources/neo-seoul/ (resolve with asset()); a key/pose is present only when its file exists.",
        "// Enemy sprites face LEFT, party (archetype) sprites face RIGHT; 512x768 canvases (bosses 768x768),",
        "// feet bottom-aligned 18px above the canvas edge.",
        "",
        "export type V2SpritePose = 'idle' | 'attack' | 'hit' | 'guard' | 'skill' | 'cover'",
        "",
        "export const V2_SPRITES: Record<string, Partial<Record<V2SpritePose, string>>> = {",
    ]
    for key, poses in sprites.items():
        lines.append(f"  {key if key.isidentifier() else q(key)}: {{")
        lines += [f"    {p}: {q(path)}," for p, path in poses.items()]
        lines.append("  },")
    lines.append("}")
    lines.append("")
    lines.append("/** EnemyDef id -> V2_SPRITES key. */")
    lines.append("export const V2_SPRITE_FOR_ENEMY: Record<string, string> = {")
    lines += [f"  {eid}: {q(key)}," for eid, key in enemy.items()]
    lines.append("}")
    lines.append("")
    lines.append("/** ArchetypeDef id -> V2_SPRITES key. */")
    lines.append("export const V2_SPRITE_FOR_ARCHETYPE: Record<string, string> = {")
    lines += [f"  {aid}: {q(key)}," for aid, key in arche.items()]
    lines.append("}")
    MANIFEST_TS.write_text("\n".join(lines) + "\n")
    print(
        f"wrote {MANIFEST_TS} ({len(sprites)} keys, {len(enemy)} enemies, {len(arche)} archetypes)"
    )


if __name__ == "__main__":
    main()
