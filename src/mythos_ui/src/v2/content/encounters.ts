// Mythos 2.0 — encounters. Pure data, hand-placed on the 7×5 board (x 0-6 → right, y 0-4 → down).
// Party deploys on x 0-1; enemies stand at x >= 4, never on cover/void, never stacked.
//
// Learning curve: `a1_n1_*` are the gentlest fights (lowest total hp) and each teaches ONE idea —
// dodge a telegraph, make enemies shoot each other, push into void, use cover against a shooter.
// `aN_n2_*` combine ideas. Acts 2 and 3 open with fights that introduce that act's new enemy mechanic.

import type { EncounterDef, Pos, Text, TileKind } from '../engine/types.ts'

const t = (ko: string, en: string): Text => ({ ko, en })
const at = (x: number, y: number): Pos => ({ x, y })
const tiles = (kind: TileKind, ...ps: [number, number][]): { pos: Pos; kind: TileKind }[] =>
  ps.map(([x, y]) => ({ pos: at(x, y), kind }))
const foe = (id: string, x: number, y: number): { id: string; pos: Pos } => ({ id, pos: at(x, y) })

